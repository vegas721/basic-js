/**
 * Given matrix where you have to find cats by ears "^^"
 *
 * @param {Array<Array>} matrix
 * @return {Number} count of cats found
 *
 * @example
 * countCats([
 *  [0, 1, '^^'],
 *  [0, '^^', 2],
 *  ['^^', 1, 2]
 * ]) => 3`
 *
 */
function countCats(matrix) {
  return matrix.reduce(
    (sum1, item) => sum1 + item.reduce((sum2, i) => sum2 + (i === "^^"), 0),
    0,
  );
}

module.exports = {
  countCats,
};
